#!/usr/bin/env python3
"""Generate src/text/nstext-case-table.h from the Unicode UnicodeData.txt
and SpecialCasing.txt.

nstext (src/text/) synthesizes small caps as Pango does, by shaping the
lowercase letters uppercased at a smaller size; Pango uppercases them with
GLib's g_utf8_strup, nstext with this table: the full uppercase mapping of
every lowercase letter (general category Ll), SpecialCasing's
unconditional mappings (U+00DF to "SS") over UnicodeData's simple ones.
From the Unicode Character Database of the version pinned below, so a
build needs neither GLib nor the network:

    curl -O https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
    curl -O https://www.unicode.org/Public/17.0.0/ucd/SpecialCasing.txt
    python3 scripts/gen-case-table.py UnicodeData.txt SpecialCasing.txt \
        src/text/nstext-case-table.h
"""
import re
import sys

UCD_VERSION = '17.0.0'


def main():
    if len(sys.argv) != 4:
        sys.exit('usage: gen-case-table.py UnicodeData.txt SpecialCasing.txt OUTPUT.h')
    data, special, out = sys.argv[1:]

    upper = {}
    lowercase = set()
    with open(data, encoding='utf-8') as f:
        for line in f:
            fields = line.rstrip('\n').split(';')
            if len(fields) < 15 or fields[2] != 'Ll':
                continue
            cp = int(fields[0], 16)
            lowercase.add(cp)
            if fields[12]:
                upper[cp] = [int(fields[12], 16)]

    version = None
    with open(special, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'^# SpecialCasing-(\d+\.\d+\.\d+)\.txt', line)
            if m:
                version = m.group(1)
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(';')]
            # code; lower; title; upper; (condition;)
            if len(fields) > 4 and fields[4]:
                continue  # language or context dependent
            cp = int(fields[0], 16)
            mapping = [int(x, 16) for x in fields[3].split()]
            if mapping != [cp]:
                upper[cp] = mapping

    if version and version != UCD_VERSION:
        sys.exit('SpecialCasing.txt is %s, expected %s' % (version, UCD_VERSION))

    # Only lowercase letters reach the table.
    entries = sorted((cp, m) for cp, m in upper.items() if cp in lowercase)
    single = [(cp, m[0]) for cp, m in entries if len(m) == 1]
    multi = [(cp, m) for cp, m in entries if len(m) > 1]
    if any(len(m) > 3 for _, m in multi):
        sys.exit('a mapping longer than three characters')

    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by scripts/gen-case-table.py from the Unicode\n'
                ' * Character Database %s, UnicodeData.txt and SpecialCasing.txt.\n'
                ' * Do not edit.\n'
                ' * Copyright 1991-2025 Unicode, Inc.; see\n'
                ' * https://www.unicode.org/license.txt (Unicode License v3).\n'
                ' * SPDX-License-Identifier: Unicode-3.0\n'
                ' */\n\n' % UCD_VERSION)
        f.write('/* The uppercase of each lowercase letter that has one, sorted:\n'
                ' * one character, */\n')
        f.write('#define NS_TEXT_UPPER_SINGLE %d\n\n' % len(single))
        f.write('static const uint32_t ns_text_upper_single[NS_TEXT_UPPER_SINGLE][2] = {\n')
        for i in range(0, len(single), 4):
            row = single[i:i + 4]
            f.write('  ' + ' '.join('{ 0x%05X, 0x%05X },' % e for e in row) + '\n')
        f.write('};\n\n')
        f.write('/* and more than one (zero-padded). */\n')
        f.write('#define NS_TEXT_UPPER_MULTI %d\n\n' % len(multi))
        f.write('static const uint32_t ns_text_upper_multi[NS_TEXT_UPPER_MULTI][4] = {\n')
        for cp, m in multi:
            m = m + [0] * (3 - len(m))
            f.write('  { 0x%05X, 0x%05X, 0x%05X, 0x%05X },\n' % (cp, m[0], m[1], m[2]))
        f.write('};\n')


if __name__ == '__main__':
    main()
