#!/usr/bin/env python3
"""Generate src/text/nstext-linebreak-table.h from the Unicode LineBreak.txt.

nstext (src/text/) breaks lines by UAX #14 with Pango's rules (break.c),
which ask for each character's Line_Break class. Pango gets it from GLib;
nstext from this table, made from the Unicode Character Database of the
version pinned below, so a build needs neither GLib nor the network:

    curl -O https://www.unicode.org/Public/17.0.0/ucd/LineBreak.txt
    python3 scripts/gen-linebreak-table.py LineBreak.txt \
        src/text/nstext-linebreak-table.h

The classes are numbered as GLib numbers GUnicodeBreakType (2.88), which
the rules' range checks (the Hangul jamo, for one) depend on.
"""
import re
import sys

UCD_VERSION = '17.0.0'

# GUnicodeBreakType's order.
CLASSES = [
    'BK', 'CR', 'LF', 'CM', 'SG', 'ZW', 'IN', 'GL', 'CB', 'SP', 'BA', 'BB',
    'B2', 'HY', 'NS', 'OP', 'CL', 'QU', 'EX', 'ID', 'NU', 'IS', 'SY', 'AL',
    'PR', 'PO', 'SA', 'AI', 'XX', 'NL', 'WJ', 'JL', 'JV', 'JT', 'H2', 'H3',
    'CP', 'CJ', 'HL', 'RI', 'EB', 'EM', 'ZWJ', 'AK', 'AP', 'AS', 'VF', 'VI',
    'HH',
]


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: gen-linebreak-table.py LineBreak.txt OUTPUT.h')
    src, out = sys.argv[1], sys.argv[2]
    index = {name: i for i, name in enumerate(CLASSES)}
    table = [index['XX']] * 0x110000
    version = None
    line_rx = re.compile(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)')
    with open(src, encoding='utf-8') as f:
        for line in f:
            if version is None:
                m = re.match(r'#\s*LineBreak-([\d.]+)\.txt', line)
                if m:
                    version = m.group(1)
            m = re.match(r'#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*(\w+)',
                         line)
            if m:
                lo, hi = int(m.group(1), 16), int(m.group(2), 16)
                cls = index[m.group(3)]
                for cp in range(lo, hi + 1):
                    table[cp] = cls
                continue
            m = line_rx.match(line)
            if not m:
                continue
            lo = int(m.group(1), 16)
            hi = int(m.group(2), 16) if m.group(2) else lo
            name = m.group(3)
            if name not in index:
                sys.exit('unknown Line_Break class %s' % name)
            for cp in range(lo, hi + 1):
                table[cp] = index[name]
    if version != UCD_VERSION:
        sys.exit('expected LineBreak-%s.txt, got %s' % (UCD_VERSION, version))

    starts, classes = [], []
    for cp, cls in enumerate(table):
        if not classes or classes[-1] != cls:
            starts.append(cp)
            classes.append(cls)

    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by scripts/gen-linebreak-table.py from the Unicode\n'
                ' * Character Database %s, LineBreak.txt. Do not edit.\n'
                ' * Copyright 1991-2025 Unicode, Inc.; see\n'
                ' * https://www.unicode.org/license.txt (Unicode License v3).\n'
                ' * SPDX-License-Identifier: Unicode-3.0\n'
                ' */\n\n' % UCD_VERSION)
        f.write('#define NS_TEXT_UCD_VERSION "%s"\n\n' % UCD_VERSION)
        f.write('/* Runs of one Line_Break class: run i covers\n'
                ' * [ns_text_lb_starts[i], ns_text_lb_starts[i + 1]). */\n')
        f.write('#define NS_TEXT_LB_RUNS %d\n\n' % len(starts))
        f.write('static const uint32_t ns_text_lb_starts[NS_TEXT_LB_RUNS] = {\n')
        for i in range(0, len(starts), 8):
            f.write('  ' + ', '.join('0x%05X' % s for s in starts[i:i + 8]) + ',\n')
        f.write('};\n\n')
        f.write('static const uint8_t ns_text_lb_classes[NS_TEXT_LB_RUNS] = {\n')
        for i in range(0, len(classes), 16):
            f.write('  ' + ', '.join('%d' % c for c in classes[i:i + 16]) + ',\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
